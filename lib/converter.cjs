const { createPlugin } = require('./runtime.cjs');
const VERSION = '1.0.0';
const HANDLERS = {
  kw: ['fetchSearchMusic', 'fetchMusicDetail'], kg: ['kgSearchMusic', 'kgMusicDetail'],
  wy: ['wySearchMusic', 'wyMusicDetail'], tx: ['txSearchMusic', 'txMusicDetail'],
  bili: ['biliSearchMusic', 'biliMusicDetail'], mg: ['mgSearchMusic', 'mgMusicDetail']
};
const NAMES = { kw: '青听酷我', kg: '青听酷狗', wy: '青听网易', tx: '青听QQ', bili: '青听哔哩哔哩', mg: '青听咪咕' };
function validate(config) {
  if (!config || !Array.isArray(config.lines)) throw new Error('Expected lines array');
  const seen = new Set();
  for (const line of config.lines) {
    if (!line || !Object.prototype.hasOwnProperty.call(HANDLERS, line.id)) throw new Error('Unsupported line id');
    if (seen.has(line.id)) throw new Error('duplicate line id: ' + line.id);
    seen.add(line.id);
    if (line.searchApi !== HANDLERS[line.id][0] || line.detailApi !== HANDLERS[line.id][1]) throw new Error('Unsupported handler: ' + line.id);
    if (typeof line.name !== 'string' || !Array.isArray(line.levels) || !line.levels.length || line.levels.some(l => typeof l !== 'string')) throw new Error('Invalid line metadata');
    if (line.enabled !== undefined && typeof line.enabled !== 'boolean') throw new Error('Invalid enabled flag');
  }
  return config;
}
function parseConfig(text) {
  // Only leading comments are permitted. Never eval remote configuration.
  let body = String(text).replace(/^\uFEFF/, '').trimStart();
  while (body.startsWith('/*') || body.startsWith('//')) {
    if (body.startsWith('/*')) {
      const end = body.indexOf('*/', 2);
      if (end < 0) throw new Error('Unterminated JSON header comment');
      body = body.slice(end + 2).trimStart();
    } else {
      const end = body.indexOf('\n');
      if (end < 0) throw new Error('Missing JSON body');
      body = body.slice(end + 1).trimStart();
    }
  }
  return validate(JSON.parse(body));
}
function compilePlugins(config, options) {
  validate(config);
  const base = new URL(options.baseUrl);
  if (base.protocol !== 'https:' || base.username || base.password || base.search || base.hash || !base.pathname.endsWith('/')) throw new Error('Expected HTTPS directory base URL');
  const gatewayUrl = options.gatewayUrl || 'https://musicserver.haitangw.cc/v1/music/resolve-url';
  if (new URL(gatewayUrl).protocol !== 'https:') throw new Error('Expected HTTPS gateway');
  const manifest = { plugins: [] };
  const scripts = {};
  for (const line of config.lines.filter(l => l.enabled !== false)) {
    const factory = options.adapters[line.id];
    if (typeof factory !== 'function') throw new Error('Missing adapter: ' + line.id);
    const filename = 'qing-' + line.id + '.js';
    const srcUrl = new URL(filename, base).href;
    const settings = { line, platform: NAMES[line.id], srcUrl, version: VERSION, gatewayUrl };
    const script = '// Generated by QingMusic → MusicFree converter. No embedded app credentials.\n' +
      '(function(){var http=require("axios");var crypto=require("crypto-js");var he=require("he");\n' +
      'module.exports=(' + createPlugin.toString() + ')(' + JSON.stringify(settings) + ',' + factory.toString() +
      ',{http:http.default||http,crypto:crypto.default||crypto,he:he.default||he});})();\n';
    scripts[filename] = script;
    manifest.plugins.push({ name: settings.platform, version: VERSION, url: srcUrl });
  }
  return { manifest, scripts };
}
module.exports = { parseConfig, compilePlugins, VERSION };
